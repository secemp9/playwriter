export type ViolationKind = 'control-byte' | 'invalid-utf8'

export type ByteViolation = {
  /** Package-root-relative path with POSIX separators. */
  file: string
  kind: ViolationKind
  /** Byte offset from the start of the file. */
  offset: number
  /** The offending byte value, 0-255. */
  byte: number
  /** 1-based line number, counting 0x0A. */
  line: number
  /** 1-based column, measured in bytes within the line. */
  column: number
  /** One-line description of what is wrong. */
  detail: string
}

function toHexByte(byte: number): string {
  return byte.toString(16).toUpperCase().padStart(2, '0')
}

/** Renders a byte as `0x1B (ESC)`, or just `0xC3` when it has no control-character name. */
export function describeByte(byte: number): string {
  const name = CONTROL_BYTE_NAMES[byte]
  return name ? `0x${toHexByte(byte)} (${name})` : `0x${toHexByte(byte)}`
}

function isDisallowedControlByte(byte: number): boolean {
  if (byte === 0x7f) {
    return true
  }
  return byte < 0x20 && !ALLOWED_CONTROL_BYTES.has(byte)
}

/**
 * Validates UTF-8 by hand rather than through TextDecoder, because TextDecoder's fatal mode
 * throws without telling you *where* the bad byte is, and the offset is half the point of this
 * check. Rejects overlong encodings, surrogate code points and anything above U+10FFFF.
 */
export function findInvalidUtf8(bytes: Uint8Array): { offset: number; byte: number; detail: string } | null {
  let index = 0
  while (index < bytes.length) {
    const lead = bytes[index]
    if (lead < 0x80) {
      index += 1
      continue
    }

    let continuationCount: number
    let minimumCodePoint: number
    let codePoint: number
    if (lead >= 0xc2 && lead <= 0xdf) {
      continuationCount = 1
      minimumCodePoint = 0x80
      codePoint = lead & 0x1f
    } else if (lead >= 0xe0 && lead <= 0xef) {
      continuationCount = 2
      minimumCodePoint = 0x800
      codePoint = lead & 0x0f
    } else if (lead >= 0xf0 && lead <= 0xf4) {
      continuationCount = 3
      minimumCodePoint = 0x10000
      codePoint = lead & 0x07
    } else {
      return {
        offset: index,
        byte: lead,
        detail:
          `0x${toHexByte(lead)} cannot start a UTF-8 sequence ` +
          (lead >= 0x80 && lead <= 0xbf
            ? '(it is a continuation byte with no lead byte before it)'
            : '(0xC0, 0xC1 and 0xF5-0xFF never appear in valid UTF-8)'),
      }
    }

    for (let step = 1; step <= continuationCount; step += 1) {
      const offset = index + step
      if (offset >= bytes.length) {
        return {
          offset: index,
          byte: lead,
          detail: `truncated ${continuationCount + 1}-byte UTF-8 sequence: the file ends mid-character`,
        }
      }
      const continuation = bytes[offset]
      if ((continuation & 0xc0) !== 0x80) {
        return {
          offset,
          byte: continuation,
          detail: `expected a UTF-8 continuation byte (0x80-0xBF) but found 0x${toHexByte(continuation)}`,
        }
      }
      codePoint = (codePoint << 6) | (continuation & 0x3f)
    }

    if (codePoint < minimumCodePoint) {
      return {
        offset: index,
        byte: lead,
        detail: `overlong UTF-8 encoding: U+${codePoint.toString(16).toUpperCase().padStart(4, '0')} written in ${continuationCount + 1} bytes`,
      }
    }
    if (codePoint >= 0xd800 && codePoint <= 0xdfff) {
      return {
        offset: index,
        byte: lead,
        detail: `UTF-8 encoding of surrogate code point U+${codePoint.toString(16).toUpperCase()}, which is not a valid character`,
      }
    }
    if (codePoint > 0x10ffff) {
      return {
        offset: index,
        byte: lead,
        detail: `UTF-8 encoding of U+${codePoint.toString(16).toUpperCase()}, which is above the Unicode maximum U+10FFFF`,
      }
    }

    index += continuationCount + 1
  }
  return null
}

/** Offsets of the first byte of every line, so line/column lookups stay cheap. */
function computeLineStarts(bytes: Uint8Array): number[] {
  const starts = [0]
  for (let index = 0; index < bytes.length; index += 1) {
    if (bytes[index] === 0x0a) {
      starts.push(index + 1)
    }
  }
  return starts
}

function lineIndexForOffset({ lineStarts, offset }: { lineStarts: number[]; offset: number }): number {
  let low = 0
  let high = lineStarts.length - 1
  while (low < high) {
    const middle = (low + high + 1) >> 1
    if (lineStarts[middle] <= offset) {
      low = middle
    } else {
      high = middle - 1
    }
  }
  return low
}

/**
 * Finds every disallowed control byte, plus the first UTF-8 well-formedness error.
 * Results are sorted by byte offset.
 */
export function findByteViolations({
  file,
  bytes,
  allowedExtraBytes = [],
}: {
  file: string
  bytes: Uint8Array
  allowedExtraBytes?: readonly number[]
}): ByteViolation[] {
  const allowed = new Set(allowedExtraBytes)
  const lineStarts = computeLineStarts(bytes)

  const locate = (offset: number): { line: number; column: number } => {
    const index = lineIndexForOffset({ lineStarts, offset })
    return { line: index + 1, column: offset - lineStarts[index] + 1 }
  }

  const violations: ByteViolation[] = []

  for (let offset = 0; offset < bytes.length; offset += 1) {
    const byte = bytes[offset]
    if (!isDisallowedControlByte(byte) || allowed.has(byte)) {
      continue
    }
    const { line, column } = locate(offset)
    violations.push({
      file,
      kind: 'control-byte',
      offset,
      byte,
      line,
      column,
      detail: `disallowed control byte ${describeByte(byte)}`,
    })
  }

  const utf8Error = findInvalidUtf8(bytes)
  if (utf8Error) {
    const { line, column } = locate(utf8Error.offset)
    violations.push({
      file,
      kind: 'invalid-utf8',
      offset: utf8Error.offset,
      byte: utf8Error.byte,
      line,
      column,
      detail: `invalid UTF-8: ${utf8Error.detail}`,
    })
  }

  violations.sort((left, right) => {
    return left.offset - right.offset
  })
  return violations
}

/**
 * Renders a byte window as text, escaping everything outside printable ASCII as \xNN so the
 * result is unambiguous and so caret alignment is exact even when the file is not valid UTF-8.
 */
function renderEscapedWindow({
  bytes,
  start,
  end,
  target,
}: {
  bytes: Uint8Array
  start: number
  end: number
  target: number
}): { text: string; caretStart: number; caretLength: number } {
  let text = ''
  let caretStart = 0
  let caretLength = 1
  for (let offset = start; offset < end; offset += 1) {
    const byte = bytes[offset]
    const chunk = byte >= 0x20 && byte <= 0x7e ? String.fromCharCode(byte) : `\\x${toHexByte(byte)}`
    if (offset === target) {
      caretStart = text.length
      caretLength = chunk.length
    }
    text += chunk
  }
  return { text, caretStart, caretLength }
}

const LINE_WINDOW_RADIUS = 48

function renderLineContext({ bytes, violation }: { bytes: Uint8Array; violation: ByteViolation }): string {
  const lineStarts = computeLineStarts(bytes)
  const index = lineIndexForOffset({ lineStarts, offset: violation.offset })
  const lineStart = lineStarts[index]
  const lineEnd = index + 1 < lineStarts.length ? lineStarts[index + 1] - 1 : bytes.length

  const windowStart = Math.max(lineStart, violation.offset - LINE_WINDOW_RADIUS)
  const windowEnd = Math.min(lineEnd, violation.offset + LINE_WINDOW_RADIUS)
  const clippedLeft = windowStart > lineStart
  const clippedRight = windowEnd < lineEnd

  const rendered = renderEscapedWindow({ bytes, start: windowStart, end: windowEnd, target: violation.offset })
  const leftMarker = clippedLeft ? '...' : ''
  const rightMarker = clippedRight ? '...' : ''
  const body = `${leftMarker}${rendered.text}${rightMarker}`
  const caretColumn = leftMarker.length + rendered.caretStart
  const caret = `${' '.repeat(caretColumn)}${'^'.repeat(rendered.caretLength)}`

  return [
    `  line ${violation.line}, rendered with every non-printable byte escaped as \\xNN:`,
    `    ${body}`,
    `    ${caret} here`,
  ].join('\n')
}

const HEX_DUMP_RADIUS = 24

function renderHexDump({ bytes, violation }: { bytes: Uint8Array; violation: ByteViolation }): string {
  const dumpStart = Math.max(0, Math.floor((violation.offset - HEX_DUMP_RADIUS) / 16) * 16)
  const dumpEnd = Math.min(bytes.length, Math.ceil((violation.offset + HEX_DUMP_RADIUS) / 16) * 16)

  const lines: string[] = [`  raw bytes around offset ${violation.offset}:`]
  for (let rowStart = dumpStart; rowStart < dumpEnd; rowStart += 16) {
    let hexPart = ''
    let asciiPart = ''
    for (let column = 0; column < 16; column += 1) {
      const offset = rowStart + column
      if (column === 8) {
        hexPart += ' '
      }
      if (offset < bytes.length) {
        hexPart += `${toHexByte(bytes[offset])} `
        const byte = bytes[offset]
        asciiPart += byte >= 0x20 && byte <= 0x7e ? String.fromCharCode(byte) : '.'
      } else {
        hexPart += '   '
        asciiPart += ' '
      }
    }
    const prefix = `    ${rowStart.toString(16).toUpperCase().padStart(8, '0')}  `
    lines.push(`${prefix}${hexPart} |${asciiPart}|`)

    if (violation.offset >= rowStart && violation.offset < rowStart + 16) {
      const column = violation.offset - rowStart
      const markerColumn = prefix.length + column * 3 + (column >= 8 ? 1 : 0)
      lines.push(`${' '.repeat(markerColumn)}^^`)
    }
  }
  return lines.join('\n')
}

function renderWhyItMatters(violation: ByteViolation): string {
  if (violation.kind === 'invalid-utf8') {
    return [
      '  Why this matters: the file is not valid UTF-8, so anything that decodes it as text -',
      '  grep, ripgrep, editors, code review diffs, the TypeScript compiler host - will either',
      '  refuse the file or silently substitute replacement characters. Re-save the file as UTF-8.',
    ].join('\n')
  }

  if (violation.byte === 0x00) {
    return [
      '  Why this matters: a raw NUL makes GNU grep classify the whole file as binary. It then',
      '  exits 1 and prints nothing at all - no match, no warning, not even "binary file matches".',
      '  `file` reports the source as `data`. tsc and vitest are entirely unaffected, so the build',
      '  stays green while every search over the file silently returns nothing. This has already',
      '  cost one afternoon and one nearly-filed false bug report.',
      '',
      '  Fix: write the escape - `\\x00` or `\\u0000` in a string or template literal - instead of',
      '  embedding the byte. A NUL separator is a fine idea; the raw byte in the source is not.',
    ].join('\n')
  }

  if (violation.byte === 0x0d) {
    return [
      '  Why this matters: this package is LF-only. A carriage return here is either a CRLF line',
      '  ending that slipped in from another platform or a lone stray CR, and both are invisible in',
      '  an editor while showing up as noise in every diff.',
      '',
      '  Fix: convert the file to LF endings, or write `\\r` if the character is genuinely part of',
      '  the data.',
    ].join('\n')
  }

  if (violation.byte === 0x1b) {
    return [
      '  Why this matters: a raw ESC byte usually means an ANSI or terminal escape sequence was',
      '  pasted in from real terminal output. It renders as nothing in an editor, so the code reads',
      '  as if the sequence is not there at all.',
      '',
      '  Fix: write `\\x1b` instead. If the raw byte is genuinely required - for example because',
      '  vitest regenerates the literal under `vitest run -u` and would overwrite the escape - add a',
      '  named entry to CONTROL_BYTE_EXCEPTIONS in src/source-bytes.ts explaining why.',
    ].join('\n')
  }

  return [
    '  Why this matters: control bytes are invisible in an editor and change how text tooling',
    '  treats the file. Only tab (0x09) and newline (0x0A) are permitted.',
    '',
    `  Fix: write the escape - \`\\x${toHexByte(violation.byte)}\` - instead of embedding the byte. If the raw byte`,
    '  is genuinely required, add a named entry to CONTROL_BYTE_EXCEPTIONS in src/source-bytes.ts',
    '  explaining why.',
  ].join('\n')
}

/**
 * The failure message. Names the file, the byte offset, the offending byte in hex, and shows
 * the surrounding bytes twice: once as escaped text with a caret under the offender, and once
 * as a hex dump. The whole point is that the next person diagnoses this in seconds rather than
 * getting silence from grep and drawing the wrong conclusion.
 */
export function formatViolation({ violation, bytes }: { violation: ByteViolation; bytes: Uint8Array }): string {
  const headline = `${violation.file}:${violation.line}:${violation.column} - ${violation.detail}`
  const facts = [
    `  offending byte: ${describeByte(violation.byte)}`,
    `  byte offset:    ${violation.offset} (line ${violation.line}, column ${violation.column})`,
    '  allowed control bytes: 0x09 (TAB) and 0x0A (LF) only',
  ].join('\n')

  return [
    headline,
    '',
    facts,
    '',
    renderLineContext({ bytes, violation }),
    '',
    renderHexDump({ bytes, violation }),
    '',
    renderWhyItMatters(violation),
  ].join('\n')
}

/** Lists every file the check will read, as package-root-relative POSIX paths, sorted. */
export function listScannedFiles({ packageRoot = PACKAGE_ROOT }: { packageRoot?: string } = {}): string[] {
  const found: string[] = []

  const visit = ({
    absoluteDir,
    relativeDir,
    recursive,
  }: {
    absoluteDir: string
    relativeDir: string
    recursive: boolean
  }): void => {
    let entries: fs.Dirent[]
    try {
      entries = fs.readdirSync(absoluteDir, { withFileTypes: true })
    } catch (error) {
      const code = (error as NodeJS.ErrnoException).code
      if (code === 'ENOENT') {
        return
      }
      throw error
    }

    for (const entry of entries) {
      // Symlinks are skipped: following them can walk out of the package or loop forever, and
      // the real file is scanned at its real location anyway.
      if (entry.isSymbolicLink()) {
        continue
      }
      const childRelative = relativeDir ? `${relativeDir}/${entry.name}` : entry.name
      if (entry.isDirectory()) {
        if (!recursive || entry.name in SKIPPED_DIRECTORIES) {
          continue
        }
        visit({ absoluteDir: path.join(absoluteDir, entry.name), relativeDir: childRelative, recursive })
        continue
      }
      if (!entry.isFile()) {
        continue
      }
      if (path.extname(entry.name).toLowerCase() in SKIPPED_EXTENSIONS) {
        continue
      }
      found.push(childRelative)
    }
  }

  for (const root of SCAN_ROOTS) {
    visit({
      absoluteDir: path.resolve(packageRoot, root.dir),
      relativeDir: root.dir === '.' ? '' : root.dir,
      recursive: root.recursive,
    })
  }

  return [...new Set(found)].sort()
}

export type ScanResult = {
  /** Every file that was read. */
  files: string[]
  /** Every violation found, in file then offset order. */
  violations: ByteViolation[]
  /** Fully formatted failure messages, at most MAX_REPORTED_PER_FILE per file. */
  reports: string[]
  /** Exception entries whose file does not exist - a rename or a typo. Always fatal. */
  missingExceptionFiles: string[]
  /** Exception entries whose file no longer contains the allowed byte. Reported, not fatal. */
  unusedExceptions: string[]
}

const MAX_REPORTED_PER_FILE = 3

/**
 * Scans the package. Pass `applyExceptions: false` to see what the tree looks like with the
 * exception list switched off, which is how the test proves the exception list is exactly the
 * set of files that actually need one.
 */
export function scanSourceBytes({
  packageRoot = PACKAGE_ROOT,
  applyExceptions = true,
}: { packageRoot?: string; applyExceptions?: boolean } = {}): ScanResult {
  const files = listScannedFiles({ packageRoot })
  const exceptionsByFile = new Map(
    CONTROL_BYTE_EXCEPTIONS.map((exception) => {
      return [exception.file, exception] as const
    }),
  )
  const usedExceptions = new Set<string>()

  const violations: ByteViolation[] = []
  const reports: string[] = []

  for (const file of files) {
    const bytes = fs.readFileSync(path.resolve(packageRoot, file))
    const exception = exceptionsByFile.get(file)

    if (exception) {
      const withoutException = findByteViolations({ file, bytes })
      const covered = withoutException.some((candidate) => {
        return candidate.kind === 'control-byte' && exception.allowedBytes.includes(candidate.byte)
      })
      if (covered) {
        usedExceptions.add(file)
      }
    }

    const allowedExtraBytes = applyExceptions && exception ? exception.allowedBytes : []
    const fileViolations = findByteViolations({ file, bytes, allowedExtraBytes })
    if (fileViolations.length === 0) {
      continue
    }

    violations.push(...fileViolations)
    for (const violation of fileViolations.slice(0, MAX_REPORTED_PER_FILE)) {
      reports.push(formatViolation({ violation, bytes }))
    }
    if (fileViolations.length > MAX_REPORTED_PER_FILE) {
      reports.push(
        `  ... and ${fileViolations.length - MAX_REPORTED_PER_FILE} more violation(s) in ${file}; ` +
          'the offsets above are the first ones.',
      )
    }
  }

  const missingExceptionFiles: string[] = []
  const unusedExceptions: string[] = []
  for (const exception of CONTROL_BYTE_EXCEPTIONS) {
    if (!fs.existsSync(path.resolve(packageRoot, exception.file))) {
      missingExceptionFiles.push(exception.file)
      continue
    }
    if (!usedExceptions.has(exception.file)) {
      unusedExceptions.push(exception.file)
    }
  }

  return { files, violations, reports, missingExceptionFiles, unusedExceptions }
}

/**
 * CLI entry point, used by `pnpm check:source-bytes` and as the first step of `pnpm build`.
 * Returns the process exit code rather than calling process.exit, so it stays testable.
 */
export function runSourceBytesCheck({ packageRoot = PACKAGE_ROOT }: { packageRoot?: string } = {}): number {
  const result = scanSourceBytes({ packageRoot })

  for (const file of result.unusedExceptions) {
    const exception = CONTROL_BYTE_EXCEPTIONS.find((candidate) => {
      return candidate.file === file
    })
    console.warn(
      `source-bytes: warning - the exception for ${file} is no longer needed; the file contains none of ` +
        `${(exception?.allowedBytes ?? []).map(describeByte).join(', ')} any more. Delete the entry from ` +
        'CONTROL_BYTE_EXCEPTIONS in src/source-bytes.ts.',
    )
  }

  if (result.missingExceptionFiles.length > 0) {
    for (const file of result.missingExceptionFiles) {
      console.error(
        `source-bytes: CONTROL_BYTE_EXCEPTIONS names ${file}, which does not exist. ` +
          'Was it renamed or deleted? Update or remove the entry in src/source-bytes.ts.',
      )
    }
    return 1
  }

  if (result.reports.length > 0) {
    console.error('')
    console.error(
      `source-bytes: ${result.violations.length} disallowed byte(s) found in ${new Set(result.violations.map((violation) => violation.file)).size} file(s).`,
    )
    console.error('')
    for (const report of result.reports) {
      console.error(report)
      console.error('')
    }
    return 1
  }

  console.log(
    `source-bytes: ${result.files.length} files checked - all valid UTF-8, no control bytes besides tab and newline.`,
  )
  return 0
}
