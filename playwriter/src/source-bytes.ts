/**
 * Source byte hygiene.
 *
 * Every source file in this package must be valid UTF-8 and must not contain control bytes
 * other than tab (0x09) and newline (0x0A).
 *
 * WHY THIS EXISTS
 * ---------------
 * A raw NUL byte was once written into a template literal in src/executor.ts. Somebody meant
 * to write the two-character escape and typed the byte instead. Nothing complained:
 *
 *   - `tsc` was clean and the file compiled.
 *   - Every vitest test passed.
 *   - `file src/executor.ts` started reporting `data` instead of text.
 *   - GNU grep silently treated the file as binary: exit code 1, no output, no
 *     "binary file matches" warning, no diagnostic of any kind.
 *
 * The last one is the expensive part. Several greps against that file came back empty, which
 * read as "this feature was never wired up" when in fact it was fully wired. There was no error
 * message anywhere in the loop, so there was nothing to diagnose - just silence. That cost an
 * afternoon and nearly produced a false bug report.
 *
 * The fix is not to ban the idea (a NUL separator in a cache key is a perfectly good idea,
 * because it cannot appear in either component) - it is to ban the raw byte. Write the escape.
 *
 * WHAT COUNTS AS A CONTROL BYTE HERE
 * ----------------------------------
 * Every byte below 0x20 except tab and newline, plus 0x7F (DEL). Carriage return (0x0D) is
 * therefore rejected too: this package is LF-only today, and a stray lone CR is exactly the
 * kind of invisible byte this check exists to surface. DEL is included because it is equally
 * invisible in an editor and equally likely to be an accident.
 *
 * Bytes 0x80 and above are only checked for UTF-8 well-formedness. The C1 control characters
 * (U+0080-U+009F) are deliberately not rejected: they are valid UTF-8, they do not make grep
 * give up, and rejecting them would flag legitimate text.
 */

