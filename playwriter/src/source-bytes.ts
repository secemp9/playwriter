export type ScanRoot = {
  /** Path relative to the package root. '.' means the package root itself. */
  dir: string
  recursive: boolean
}

/**
 * What "tracked source file" means for this check.
 *
 * The scan walks the filesystem rather than asking `git ls-files`, on purpose:
 *
 *   - A brand-new file that has not been staged yet is exactly when this mistake gets made
 *     (you just typed the byte, you have not committed anything). `git ls-files` cannot see
 *     that file; a filesystem walk can, and catches the problem at the earliest moment.
 *   - It works without a git checkout at all - a published tarball, a shallow export, a CI
 *     job that copies the tree.
 *
 * The roots below cover every directory in this package that holds hand-written text, plus the
 * package root itself (non-recursively) for the config and entry files that live there:
 * package.json, tsconfig.json, vitest.config.ts, vitest.setup.ts, bin.js, CHANGELOG.md.
 *
 * dist/ is out of scope: it is generated. Any bad byte in dist/ came from src/, where this
 * check will already have caught it, and dist/ additionally contains bundled third-party code
 * that this package does not author. The committed binary fixtures (test/video-golden/*.png)
 * stay in scope as *files* but are skipped by extension - a check that fails on a legitimately
 * binary PNG is a check people turn off.
 */
export const SCAN_ROOTS: readonly ScanRoot[] = [
  { dir: '.', recursive: false },
  { dir: 'src', recursive: true },
  { dir: 'scripts', recursive: true },
  { dir: 'test', recursive: true },
  { dir: 'docs', recursive: true },
]

export type ByteException = {
  /** Path relative to the package root, POSIX separators. Exact match - no globs, no patterns. */
  file: string
  /**
   * The exact byte values tolerated in this file, on top of tab and newline.
   * NUL (0x00) can never be listed here; see the assertion below.
   */
  allowedBytes: readonly number[]
  /** Why the raw byte belongs in this file. Required. */
  reason: string
}

/**
 * Files allowed to contain specific raw control bytes.
 *
 * Deliberately a list of exact filenames with exact byte values, never a pattern. A rule like
 * "*.test.ts may contain control bytes" or "files that already contain ESC are fine" would let
 * a stray NUL through in every place where it actually matters. Narrowing the exception to the
 * one byte value each file genuinely needs means an accidental NUL in one of these two files
 * still fails the check.
 *
 * Adding a file here should be uncomfortable. Write down why.
 */
export const CONTROL_BYTE_EXCEPTIONS: readonly ByteException[] = [
  {
    file: 'src/kitty-graphics.test.ts',
    allowedBytes: [0x1b],
    reason:
      'Contains a vitest toMatchInlineSnapshot() of buildKittySequence() output, which is a kitty ' +
      'graphics APC sequence and therefore literally is ESC _G ... ESC backslash. vitest writes its own ' +
      'inline snapshots and `pnpm test` runs `vitest run -u`, so replacing the raw byte with a \\x1b ' +
      'escape would be undone on the very next test run. The ESC bytes are the value under test. ' +
      'Every other escape in that file is written as \\x1b, as it should be.',
  },
  // src/relay-core.test.ts used to be here, for the ESC [2m ... ESC [22m dim codes in the
  // inline snapshots of Playwright's "Call log:" output. Those three snapshots have been
  // replaced by explicit toContain() assertions on the message and on the deterministic head
  // of the call log — they had pinned the retry tail, which is a function of machine speed —
  // and the assertions match the text inside the dim codes rather than the codes themselves.
  // No raw ESC is left in the file, so the exception is gone rather than merely unused.
]

// Structural guarantee: no exception can ever whitelist NUL, which is the byte that started
// all of this and the one that makes grep give up without saying anything.
for (const exception of CONTROL_BYTE_EXCEPTIONS) {
  if (exception.allowedBytes.includes(0x00)) {
    throw new Error(
      `CONTROL_BYTE_EXCEPTIONS entry for ${exception.file} lists NUL (0x00). ` +
        'NUL is never allowed in a source file: it makes grep treat the file as binary and return ' +
        'nothing at all, with no warning. Write the escape instead.',
    )
  }
  if (exception.allowedBytes.length === 0) {
    throw new Error(`CONTROL_BYTE_EXCEPTIONS entry for ${exception.file} lists no bytes; remove the entry instead.`)
  }
  if (!exception.reason.trim()) {
    throw new Error(`CONTROL_BYTE_EXCEPTIONS entry for ${exception.file} has an empty reason; explain why.`)
  }
}

